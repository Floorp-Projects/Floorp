/**
 * # Chrome extras — the Lepton toggles, without Lepton
 *
 * Floorp's settings used to expose 25 UI toggles ("Lepton の設定") whose values
 * were stored as individual `userChrome.*` bool prefs and whose CSS lived inside
 * the vendored Lepton stylesheet as `@media (-moz-bool-pref: "userChrome.X")`
 * blocks. That meant:
 *
 *   - the toggles only existed for the three Lepton-family designs (`lepton`,
 *     `photon`, `protonfix`); `fluerial` and `proton` had no equivalent;
 *   - the feature was coupled to a file that `update_lepton.yml` re-syncs from
 *     upstream every day, so any Floorp-side edit could be silently deleted;
 *   - vendored Lepton mixes `-moz-bool-pref` and a bare `-moz-pref(...)` form,
 *     and one toggle (`urlViewAlwaysShowPageActions`) pointed at a pref name
 *     Lepton never read, so it never did anything.
 *
 * This module is the new home. The settings values live in the regular design
 * config (`floorp.design.configs` → `uiCustomization.chromeExtras`), and the CSS
 * lives in `chrome-extras-css/*.css` with every pref gate removed.
 * `ui-custom/styles/style-manager.ts` decides, in JS, which sheets to inject —
 * so the feature works on **every** design.
 *
 * The CSS is imported with *relative* paths on purpose. `bridge/loader-features`
 * bundles through the `link-features-chrome` symlink, so a `#features-chrome/...`
 * import with a `?inline` query does not resolve, and a relative path that leaves
 * the `designs/` directory resolves to the wrong place.
 *
 * ## Where the CSS comes from
 *
 * Each `chrome-extras-*.css` file is generated by
 * `tools/gen-chrome-extras.py` from `browser-features/skin/lepton/css/
 * leptonChrome.css`. Run it from `browser-features/skin/lepton/css`:
 *
 *     python3 ../../../../tools/gen-chrome-extras.py
 *
 * The generator only takes blocks that gate on a single Lepton toggle; blocks
 * that AND several toggles together are layout combinations. The sidebar
 * overlap/auto-hide combination has its own sheet; the other combinations are
 * left to the native implementations. Omissions are listed in generated file
 * headers so the divergence from upstream stays auditable.
 *
 * Three keys are Floorp-native rather than ported — `autohideNavbar`,
 * `tabbarAsTitlebar` and `tabbarOneLiner`. Lepton implements them inside ~2,500
 * lines of nested gates over its own `--uc-*` layout variables; see the comments
 * in those files for what was kept, what was inlined, and what was dropped.
 *
 * The `hiddenTab*` toggles other than `hiddenTabIcon` are Floorp-only.
 */

