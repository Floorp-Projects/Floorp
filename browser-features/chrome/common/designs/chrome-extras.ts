/** Layout rules selected by the sidebar toggle combination. */
export const CHROME_EXTRAS_SIDEBAR_VARIANTS = {
  autohideOnly: autohideSidebarOnlyCSS,
  overlapOnly: sidebarOverlapOnlyCSS,
  combined: sidebarOverlapAutohideCSS,
} as const;

/** Toggles that only make sense while the Lepton icon rules are active. */
const ICON_DEPENDENT_KEYS: ReadonlySet<ChromeExtrasKey> = new Set([
  "iconMenu",
]);

/**
 * Assemble the single chrome-extras stylesheet for the given settings.
 *
 * Returns the scaffold, the base icon rules while icons are enabled, and every
 * enabled toggle's rules in `CHROME_EXTRAS_KEYS` order. `iconDisabled` has the
 * opposite polarity from the other toggles: its sheet comes from Lepton's
 * `not userChrome.icon.disabled` blocks. Outside the Lepton family, the base
 * icons require an explicit `iconMenu` choice so a fresh design stays intact.
 */
export function buildChromeExtrasCSS(
  settings: ChromeExtrasSettings,
  design: string,
): string {
  // Lepton already shows its icon set by default. Other designs keep their
  // original appearance until the user opts into menu icons.
  const iconsEnabled = !settings.iconDisabled &&
    (isLeptonFamilyDesign(design) || settings.iconMenu);
  const parts: string[] = [CHROME_EXTRAS_SCAFFOLD_CSS];

  for (const key of CHROME_EXTRAS_KEYS) {
    if (key === "iconDisabled") {
      if (iconsEnabled) {
        parts.push(CHROME_EXTRAS_CSS.iconDisabled);
      }
      continue;
    }
    if (!settings[key]) {
      continue;
    }
    if (ICON_DEPENDENT_KEYS.has(key) && !iconsEnabled) {
      continue;
    }
    parts.push(CHROME_EXTRAS_CSS[key]);
  }

  if (settings.autohideSidebar && settings.sidebarOverlap) {
    parts.push(CHROME_EXTRAS_SIDEBAR_VARIANTS.combined);
  } else if (settings.autohideSidebar) {
    parts.push(CHROME_EXTRAS_SIDEBAR_VARIANTS.autohideOnly);
  } else if (settings.sidebarOverlap) {
    parts.push(CHROME_EXTRAS_SIDEBAR_VARIANTS.overlapOnly);
  }

  return parts.join("\n");
}
