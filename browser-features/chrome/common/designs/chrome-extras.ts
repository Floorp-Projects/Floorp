/**
 * Lepton icon base path, mirroring `getIconBasePath()` in `utils/css.ts`.
 * Lepton's icon rules use a relative `../icons/...`, which does not resolve once
 * the CSS is injected into the chrome document, so it is rewritten here.
 */
function leptonIconBasePath(): string {
  if (import.meta.env.DEV) {
    return "http://localhost:5174/lepton/icons";
  }
  return "chrome://noraneko-skin/content/lepton/icons";
}

function resolveIcons(css: string): string {
  return css.replaceAll("../icons", leptonIconBasePath());
}

