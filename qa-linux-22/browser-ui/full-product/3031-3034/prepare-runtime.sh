#!/bin/bash
set -euo pipefail
stage=/workspace/full-product-3031-3034
cd "$stage/runtime"
if test -L noraneko;then test "$(readlink noraneko)" = ../noraneko;else ln -s ../noraneko noraneko;fi
for patch in .github/patches/upstream/*.patch; do
 test -e "$patch" || continue
 if git apply --reverse --check "$patch" >/dev/null 2>&1;then echo "Already applied upstream patch: $patch";continue;fi
 git apply --check "$patch"
 git apply --verbose "$patch"
done
for patch in noraneko/.github/patches/floorp-runtime/common/*.patch;do
 test -e "$patch" || continue
 if git apply --reverse --check "$patch" >/dev/null 2>&1;then echo "Already applied common patch: $patch";continue;fi
 git apply --check "$patch"
 git apply --verbose "$patch"
done
cp -r .github/assets/branding/* browser/branding/
(cd noraneko && PATH=/workspace/.floorp-cloud/tools/node_modules/.bin:$PATH DENO_DIR=/workspace/.floorp-cloud/deno-cache deno task feles-build misc writeVersion)
mkdir -p noraneko/static/gecko/config/autogenerated
printf '%s@%s\n' "$(cat noraneko/static/gecko/config/version.txt)" "$(cat browser/config/version.txt)" > noraneko/static/gecko/config/autogenerated/version.txt
printf '%s@%s\n' "$(cat noraneko/static/gecko/config/version_display.txt)" "$(cat browser/config/version_display.txt)" > noraneko/static/gecko/config/autogenerated/version_display.txt
cp .github/workflows/mozconfigs/linux-x86_64.mozconfig mozconfig
sed -i '/^[[:space:]]*ac_add_options --disable-updater/d;/^[[:space:]]*ac_add_options --enable-unverified-updates/d;/^[[:space:]]*ac_add_options --enable-chrome-format=flat/d;/^[[:space:]]*ac_add_options --enable-update-channel=/d;/^[[:space:]]*ac_add_options --with-branding=/d' mozconfig
cat >> mozconfig <<EOF
ac_add_options --with-version-file-path=noraneko/static/gecko/config/autogenerated
ac_add_options --enable-release
ac_add_options --disable-tests
ac_add_options --enable-artifact-builds
mk_add_options MOZ_OBJDIR=$stage/obj-artifact-build-output
ac_add_options --enable-update-channel=release
ac_add_options --with-branding=browser/branding/floorp-official
EOF
sed -i 's|MOZ_BRANDING_DIRECTORY=browser/branding/unofficial|MOZ_BRANDING_DIRECTORY=browser/branding/floorp-official|g' browser/confvars.sh
if test -f toolkit/modules/UpdateUtils.sys.mjs; then
 sed -i 's|return encodeURIComponent(replacement);|return name === "NORA_UPDATE_HOST" ? replacement : encodeURIComponent(replacement);|' toolkit/modules/UpdateUtils.sys.mjs
 sed -i 's|REPLACE_THIS_NORA_UPDATE_HOST_TARGET_PLACEHOLDER|updates.floorp.app/browser/stable/Linux/x86_64/|g' toolkit/modules/UpdateUtils.sys.mjs
fi
