#!/bin/bash
# Local-only canonical artifact assembly. No release, uploads or source CSS injection.
# Requires independent matching Runtime checkout at root/runtime, PR3033 checkout
# at root/noraneko, Deno dependencies and exact verified native artifact.
set -euo pipefail
root=${QA_PRODUCT_ROOT:-/workspace/product3033}
artifact=${QA_RUNTIME_ARTIFACT:-/workspace/qa-linux-22/browser-ui/full-product/3033/runtime.tar.xz}
export PATH=/workspace/.floorp-cloud/tools/node_modules/.bin:$PATH
export DENO_DIR=/workspace/.floorp-cloud/deno-cache
export MOZBUILD_STATE_PATH=/workspace/.floorp-cloud/mozbuild
cd "$root/noraneko"
deno task feles-build misc writeVersion
NODE_ENV=production deno task feles-build build --phase before-mach
cd "$root/runtime"
test -e noraneko || ln -s ../noraneko noraneko
for patch in .github/patches/upstream/*.patch ../noraneko/.github/patches/floorp-runtime/common/*.patch; do
 if ! git apply --reverse --check "$patch" >/dev/null 2>&1; then git apply --check "$patch";git apply "$patch";fi
done
cp .github/workflows/mozconfigs/linux-x86_64.mozconfig mozconfig
sed -i '/^[[:space:]]*ac_add_options --enable-unverified-updates/d' mozconfig
mkdir -p ../noraneko/static/gecko/config/autogenerated
for kind in version version_display; do
 printf '%s@%s\n' "$(cat ../noraneko/static/gecko/config/$kind.txt)" "$(cat browser/config/$kind.txt)" > "../noraneko/static/gecko/config/autogenerated/$kind.txt"
done
cat >> mozconfig <<CONFIG
ac_add_options --with-version-file-path=noraneko/static/gecko/config/autogenerated
ac_add_options --enable-release
ac_add_options --disable-tests
ac_add_options --enable-artifact-builds
mk_add_options MOZ_OBJDIR=$root/obj-artifact-build-output
CONFIG
./mach configure
for patch in .github/patches/packaging/*.patch; do
 if ! git apply --reverse --check "$patch" >/dev/null 2>&1; then git apply --check "$patch";git apply "$patch";fi
done
MOZ_ARTIFACT_FILE="$artifact" ./mach build
cd ../noraneko
CANON_PLATFORM=Linux-x86_64 deno task feles-build build --phase after-mach
# Detach build symlinks before built-file patching, as package.yml does.
cp -aL ../obj-artifact-build-output/dist/bin ../obj-artifact-build-output/dist/bin-detached
mv ../obj-artifact-build-output/dist/bin ../obj-artifact-build-output/dist/bin-source-links
mv ../obj-artifact-build-output/dist/bin-detached ../obj-artifact-build-output/dist/bin
for patch in tools/patches/*.patch; do
 case "$patch" in *.windows.patch|*.darwin.patch) continue;; esac
 target="$root/obj-artifact-build-output/dist/bin"
 if ! git apply --reverse --directory "$target" --unsafe-paths --check "$patch" >/dev/null 2>&1; then git apply --directory "$target" --unsafe-paths --check "$patch";git apply --directory "$target" --unsafe-paths "$patch";fi
done
cp _dist/buildid2 ../obj-artifact-build-output/dist/bin/browser/buildid2
# Do NOT run override.ini: it sets xpinstall.signatures.required=false.
# Keep strict checks. Current exact native artifact lacks the XPT companion;
# this command is expected to stop with the preserved package.log failure.
cd ../runtime
./mach package
