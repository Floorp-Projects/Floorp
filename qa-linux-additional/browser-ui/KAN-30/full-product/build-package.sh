#!/bin/bash
set -euo pipefail
stage=/workspace/kan30-full
qa=/workspace/qa-linux-additional/browser-ui/KAN-30/full-product
# This script is run in its own user+mount namespace. No shared source can be written.
mount --bind /workspace/full-product-3031-3034/runtime "$stage/runtime"
mount -o remount,bind,ro "$stage/runtime"
test "$(readlink -f "$stage/runtime/noraneko")" = "$stage/noraneko"
if touch "$stage/runtime/qa-must-not-write" 2>/dev/null;then echo 'readonly protection failed';exit 2;fi
export PATH="/workspace/.floorp-cloud/tools/node_modules/.bin:/workspace/.floorp-cloud/go/bin:/workspace/full-product-3031-3034/mozbuild/node/bin:$PATH"
export DENO_DIR=/workspace/.floorp-cloud/deno-cache DENO_TLS_CA_STORE=system
export MOZBUILD_STATE_PATH="$stage/mozbuild" MOZCONFIG="$stage/mozconfig" GIT_OPTIONAL_LOCKS=0
export REQUESTS_CA_BUNDLE=/etc/ssl/certs/ca-certificates.crt PIP_CERT=/etc/ssl/certs/ca-certificates.crt
cd "$stage/noraneko"
deno task feles-build misc writeVersion > "$qa/logs/version.log" 2>&1
mkdir -p static/gecko/config/autogenerated
for kind in version version_display;do printf '%s@%s\n' "$(cat static/gecko/config/$kind.txt)" "$(cat "$stage/runtime/browser/config/$kind.txt")" > "static/gecko/config/autogenerated/$kind.txt";done
cd "$stage/runtime"
# Applied production patches must already match this read-only native source.
for patch in "$stage/noraneko"/.github/patches/floorp-runtime/common/*.patch;do git apply --reverse --check "$patch";done
./mach configure > "$qa/logs/configure.log" 2>&1
MOZ_ARTIFACT_FILE=/workspace/qa-linux-22/browser-ui/full-product/shared/floorp-linux-x86_64-moz-artifact.tar.xz ./mach build > "$qa/logs/mach-build.log" 2>&1
cd "$stage/noraneko"
CANON_PLATFORM=Linux-x86_64 NODE_ENV=production deno task feles-build build --phase after-mach > "$qa/logs/after-mach.log" 2>&1
# Continue with verified flattening and genuine XPT supply only after successful build.
echo ASSEMBLY_READY
