#!/usr/bin/env bash
# Linux x64 release assembly of .github/workflows/package.yml around a given Runtime package.
set -euo pipefail
RT_ARTIFACT="${1:?compiled Runtime package (.tar.xz)}"
RUNTIME_REPO="${2:?Runtime repository holding the locked commit}"
FLOORP="${3:?Floorp checkout at the commit under test}"
W="${4:?new assembly directory}"
commit=$(python3 -c 'import json,sys;print(json.load(open(sys.argv[1]))["source"]["commit"])' "$FLOORP/floorp-runtime.lock.json")
git -C "$RUNTIME_REPO" worktree add --detach "$W" "$commit"
cd "$W"
for p in .github/patches/upstream/*.patch; do git apply --verbose "$p"; done
git -C "$FLOORP" worktree add --detach "$W/noraneko" HEAD
for p in noraneko/.github/patches/floorp-runtime/common/*.patch; do
  if git apply --reverse --check "$p" >/dev/null 2>&1; then continue; fi
  git apply --check "$p"; git apply --verbose "$p"
done
(cd noraneko && deno install --allow-scripts)
./mach --no-interactive bootstrap --application-choice browser_artifact_mode
(cd noraneko && deno task feles-build misc writeVersion)
if [ -d .github/assets/branding ]; then cp -r .github/assets/branding/* ./browser/branding/; fi
cp .github/workflows/mozconfigs/linux-x86_64.mozconfig mozconfig
if [ -d ./noraneko/static/gecko/branding ]; then cp -r ./noraneko/static/gecko/branding/* ./browser/branding/; fi
mkdir -p ./noraneko/static/gecko/config/autogenerated
cat >> mozconfig <<'EOM'
ac_add_options --with-version-file-path=noraneko/static/gecko/config/autogenerated
ac_add_options --enable-release
ac_add_options --disable-tests
ac_add_options --enable-artifact-builds
mk_add_options MOZ_OBJDIR=./obj-artifact-build-output
EOM
sed -i 's|^[[:space:]]*ac_add_options --disable-updater.*$||g;s|^[[:space:]]*ac_add_options --enable-unverified-updates.*$||g;s|^[[:space:]]*ac_add_options --enable-chrome-format=flat.*$||g;s|^[[:space:]]*ac_add_options --enable-update-channel=.*$||g;s|^[[:space:]]*ac_add_options --with-branding=.*$||g' mozconfig
UU=./toolkit/modules/UpdateUtils.sys.mjs
sed -i 's|return encodeURIComponent(replacement);|return name === "NORA_UPDATE_HOST" ? replacement : encodeURIComponent(replacement);|' "$UU"
sed -i "s|MOZ_BRANDING_DIRECTORY=browser/branding/unofficial|MOZ_BRANDING_DIRECTORY=browser/branding/floorp-official|g" ./browser/confvars.sh
echo "ac_add_options --enable-update-channel=release" >> mozconfig
echo "ac_add_options --with-branding=browser/branding/floorp-official" >> mozconfig
sed -i "s|REPLACE_THIS_NORA_UPDATE_HOST_TARGET_PLACEHOLDER|updates.floorp.app/browser/stable/Linux/x86_64/|g" "$UU"
./mach configure
git apply --ignore-space-change --ignore-whitespace .github/patches/packaging/*.patch
(cd noraneko && NODE_ENV=production deno task feles-build build --phase before-mach)
./mach configure
MOZ_ARTIFACT_FILE="$RT_ARTIFACT" ./mach build
DIST_ROOT="$W/obj-artifact-build-output/dist"; PT="$DIST_ROOT/bin"
(cd noraneko && CI=true deno task feles-build build --phase after-mach
 rsync -aL "$PT/" "$DIST_ROOT/tmp__bin"; rm -rf "$PT"; mv "$DIST_ROOT/tmp__bin" "$PT"
 for pf in ./tools/patches/*.patch; do
   case "$pf" in *.windows.patch|*.darwin.patch) continue;; esac
   if git apply --reverse --directory "$PT" --unsafe-paths --check "$pf"; then :; else
     git apply --directory "$PT" --unsafe-paths --check "$pf"; git apply --directory "$PT" --unsafe-paths "$pf"; fi
 done
 if [ -f _dist/buildid2 ]; then mkdir -p "$PT/browser"; cp _dist/buildid2 "$PT/browser/buildid2"; fi
 ./static/gecko/pref/override.sh ../obj-artifact-build-output/dist/bin/browser/defaults/preferences/firefox.js)
patchelf --add-rpath '$ORIGIN' ./obj-artifact-build-output/dist/bin/updater
sed -i 's/--error-if-empty -C/-C/g' ./toolkit/mozapps/installer/packager.mk
./mach package
ls obj-artifact-build-output/dist/floorp-*.tar.xz
