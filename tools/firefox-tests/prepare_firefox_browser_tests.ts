import { parseArgs } from "@std/cli";
import * as path from "@std/path";
import {
  loadRuntimeLock,
  type RuntimeLock,
  type RuntimePreference,
  type RuntimeTest,
  type RuntimeTestManifest,
} from "../src/runtime_lock.ts";

interface FirefoxTestCollectionManifest {
  schemaVersion: number;
  mode?: "candidate" | "locked";
  source?: {
    repository?: string;
    ref?: string;
    commit?: string;
    tree?: string;
  };
  files?: Array<{
    path: string;
    outputPath: string;
    size: number;
    sha256: string;
    mode: string;
    gitBlob: string;
    roles?: string[];
    harnesses?: string[];
  }>;
}

type MarkerPreference =
  | { name: string; kind: "bool"; value: boolean }
  | { name: string; kind: "int"; value: number }
  | { name: string; kind: "string"; value: string };

interface PreparedFirefoxBrowserTest {
  upstreamPath: string;
  manifestPath: string;
  wrapperPath: string;
  importSpecifier: string;
  expectedTaskCount: number;
  prefs: MarkerPreference[];
  headPolicy: "harness-replaced";
  supportPolicy: "locked-not-loaded";
}

interface PrepareFirefoxBrowserTestsOptions {
  collectionDir: string;
  outputDir: string;
  runtimeLock?: RuntimeLock;
}

interface PreparedFirefoxBrowserTestsManifest {
  schemaVersion: 1;
  source: {
    repository: string;
    ref: string;
    commit: string;
    tree: string;
  };
  tests: PreparedFirefoxBrowserTest[];
}

const DEFAULT_COLLECTION_DIR = "_dist/firefox-tests";
const DEFAULT_OUTPUT_DIR =
  "browser-features/chrome/test/firefox-downloaded/generated";

function ensureString(value: unknown, name: string): string {
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(`${name} is required`);
  }
  return value;
}

async function readJsonFile<T>(filePath: string): Promise<T> {
  const raw = await Deno.readTextFile(filePath);
  return JSON.parse(raw) as T;
}

function sanitizeName(value: string): string {
  return value
    .replace(/\.[^.]+$/, "")
    .replace(/[^A-Za-z0-9_-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();
}

function wrapperNameForTest(test: RuntimeTest): string {
  const baseName = sanitizeName(test.path.split("/").join("__"));
  if (!baseName) {
    throw new Error(`Could not derive wrapper name for ${test.path}`);
  }
  return `${baseName}.test.js`;
}

function markerPreference(preference: RuntimePreference): MarkerPreference {
  switch (preference.type) {
    case "boolean":
      return {
        name: preference.name,
        kind: "bool",
        value: preference.value,
      };
    case "integer":
      return {
        name: preference.name,
        kind: "int",
        value: preference.value,
      };
    case "string":
      return {
        name: preference.name,
        kind: "string",
        value: preference.value,
      };
  }
}

function buildWrapperSource(
  test: RuntimeTest,
  manifest: RuntimeTestManifest,
): string {
  const importSpecifier = `#firefox-tests/${test.path}`;
  const prefs = manifest.preferences.map(markerPreference);
  return [
    "// SPDX-License-Identifier: MPL-2.0",
    "// @colocated-env browser",
    "// @ts-nocheck",
    "//",
    "// Generated by tools/firefox-tests/prepare_firefox_browser_tests.ts.",
    "// Do not edit; floorp-runtime.lock.json is the sole authority.",
    `// Upstream path: ${test.path}`,
    "",
    "export const __NORA_DOWNLOADED_FIREFOX_TEST__ = {",
    "  schemaVersion: 1,",
    `  upstreamPath: ${JSON.stringify(test.path)},`,
    `  manifestPath: ${JSON.stringify(test.manifest)},`,
    `  expectedTaskCount: ${test.expectedTasks},`,
    `  prefs: ${JSON.stringify(prefs)},`,
    `  headPolicy: ${JSON.stringify(test.headPolicy)},`,
    `  supportPolicy: ${JSON.stringify(test.supportPolicy)},`,
    `  load: () => import(${JSON.stringify(importSpecifier)}),`,
    "};",
    "",
  ].join("\n");
}

async function shaHex(
  algorithm: "SHA-1" | "SHA-256",
  bytes: Uint8Array,
): Promise<string> {
  const input = new Uint8Array(bytes.byteLength);
  input.set(bytes);
  const digest = await crypto.subtle.digest(algorithm, input);
  return [...new Uint8Array(digest)]
    .map((byte) => byte.toString(16).padStart(2, "0"))
    .join("");
}

async function gitBlobHex(bytes: Uint8Array): Promise<string> {
  const prefix = new TextEncoder().encode(`blob ${bytes.byteLength}\0`);
  const input = new Uint8Array(prefix.byteLength + bytes.byteLength);
  input.set(prefix);
  input.set(bytes, prefix.byteLength);
  return await shaHex("SHA-1", input);
}

async function listRelativeFiles(
  root: string,
  current = root,
): Promise<string[]> {
  const entries = [...Deno.readDirSync(current)].sort((left, right) =>
    left.name.localeCompare(right.name)
  );
  const files: string[] = [];
  for (const entry of entries) {
    const entryPath = path.join(current, entry.name);
    if (entry.isDirectory) {
      files.push(...await listRelativeFiles(root, entryPath));
    } else if (entry.isFile) {
      files.push(path.relative(root, entryPath).replaceAll("\\", "/"));
    } else {
      throw new Error(`Collected material is not a regular file: ${entryPath}`);
    }
  }
  return files.sort((left, right) => left.localeCompare(right));
}

function assertExactPaths(
  actual: string[],
  expected: string[],
  description: string,
): void {
  const actualSet = new Set(actual);
  const expectedSet = new Set(expected);
  const missing = expected.filter((value) => !actualSet.has(value));
  const extra = actual.filter((value) => !expectedSet.has(value));
  if (missing.length > 0 || extra.length > 0) {
    throw new Error(
      `${description} mismatch (missing: ${
        missing.join(", ") || "none"
      }; extra: ${extra.join(", ") || "none"})`,
    );
  }
  if (actual.length !== actualSet.size) {
    throw new Error(`${description} contains duplicate paths`);
  }
}

async function assertLockedCollection(
  collectionDir: string,
  collection: FirefoxTestCollectionManifest,
  lock: RuntimeLock,
): Promise<void> {
  if (collection.schemaVersion !== 1) {
    throw new Error(
      `Unsupported Firefox test collection schema: ${collection.schemaVersion}`,
    );
  }
  if (collection.mode !== "locked") {
    throw new Error(
      `Downloaded Firefox wrappers require a locked collection; got ${
        collection.mode ?? "unknown"
      }`,
    );
  }
  const expectedSource = lock.source;
  const actualSource = collection.source;
  for (
    const [field, expected] of [
      ["repository", expectedSource.repository],
      ["ref", expectedSource.ref],
      ["commit", expectedSource.commit],
      ["tree", expectedSource.tree],
    ] as const
  ) {
    if (actualSource?.[field] !== expected) {
      throw new Error(
        `Firefox test collection source ${field} mismatch: expected ${expected}, got ${
          actualSource?.[field] ?? "missing"
        }`,
      );
    }
  }

  if (!Array.isArray(collection.files)) {
    throw new Error("Firefox test collection manifest has no files array");
  }
  const expectedPaths = lock.source.materials.entries.map((entry) =>
    entry.path
  );
  const collectionPaths = collection.files.map((entry) => entry.path);
  assertExactPaths(collectionPaths, expectedPaths, "Collection manifest files");

  const filesByPath = new Map(
    collection.files.map((entry) => [entry.path, entry]),
  );
  for (const material of lock.source.materials.entries) {
    const file = filesByPath.get(material.path);
    if (!file) {
      throw new Error(`Locked Firefox material is missing: ${material.path}`);
    }
    const expectedOutputPath = `files/${material.path}`;
    if (
      file.outputPath !== expectedOutputPath || file.size !== material.bytes ||
      file.sha256 !== material.sha256 || file.mode !== material.mode ||
      file.gitBlob !== material.gitBlob
    ) {
      throw new Error(
        `Collection metadata does not match the Runtime lock for ${material.path}`,
      );
    }

    const filePath = path.join(
      collectionDir,
      ...expectedOutputPath.split("/"),
    );
    const bytes = await Deno.readFile(filePath).catch((error) => {
      if (error instanceof Deno.errors.NotFound) {
        return null;
      }
      throw error;
    });
    if (!bytes) {
      throw new Error(`Collected Firefox material is missing: ${filePath}`);
    }
    const sha256 = await shaHex("SHA-256", bytes);
    const gitBlob = await gitBlobHex(bytes);
    if (
      bytes.byteLength !== material.bytes || sha256 !== material.sha256 ||
      gitBlob !== material.gitBlob
    ) {
      throw new Error(
        `Collected Firefox material content mismatch: ${material.path}`,
      );
    }
  }

  const filesRoot = path.join(collectionDir, "files");
  const physicalPaths = await listRelativeFiles(filesRoot);
  assertExactPaths(physicalPaths, expectedPaths, "Collected material files");
}

export async function prepareFirefoxBrowserTests(
  options: PrepareFirefoxBrowserTestsOptions,
): Promise<PreparedFirefoxBrowserTestsManifest> {
  const collectionDir = path.resolve(options.collectionDir);
  const outputDir = path.resolve(options.outputDir);
  const lock = options.runtimeLock ?? await loadRuntimeLock();
  const collectionManifest = await readJsonFile<FirefoxTestCollectionManifest>(
    path.join(collectionDir, "manifest.json"),
  );
  await assertLockedCollection(collectionDir, collectionManifest, lock);

  const manifestsByPath = new Map(
    lock.source.tests.manifests.map((manifest) => [manifest.path, manifest]),
  );
  const wrapperNames = new Set<string>();
  const preparedTests = lock.source.tests.entries.map((test) => {
    const manifest = manifestsByPath.get(test.manifest);
    if (!manifest) {
      throw new Error(`Locked manifest is missing for ${test.path}`);
    }
    const wrapperPath = wrapperNameForTest(test);
    if (wrapperNames.has(wrapperPath)) {
      throw new Error(`Duplicate generated wrapper name: ${wrapperPath}`);
    }
    wrapperNames.add(wrapperPath);
    return {
      upstreamPath: test.path,
      manifestPath: test.manifest,
      wrapperPath,
      importSpecifier: `#firefox-tests/${test.path}`,
      expectedTaskCount: test.expectedTasks,
      prefs: manifest.preferences.map(markerPreference),
      headPolicy: test.headPolicy,
      supportPolicy: test.supportPolicy,
    } satisfies PreparedFirefoxBrowserTest;
  });

  await Deno.remove(outputDir, { recursive: true }).catch((error) => {
    if (!(error instanceof Deno.errors.NotFound)) {
      throw error;
    }
  });
  await Deno.mkdir(outputDir, { recursive: true });

  for (const test of lock.source.tests.entries) {
    const manifest = manifestsByPath.get(test.manifest);
    if (!manifest) {
      throw new Error(`Locked manifest is missing for ${test.path}`);
    }
    await Deno.writeTextFile(
      path.join(outputDir, wrapperNameForTest(test)),
      buildWrapperSource(test, manifest),
    );
  }

  const preparedManifest: PreparedFirefoxBrowserTestsManifest = {
    schemaVersion: 1,
    source: {
      repository: lock.source.repository,
      ref: lock.source.ref,
      commit: lock.source.commit,
      tree: lock.source.tree,
    },
    tests: preparedTests,
  };
  await Deno.writeTextFile(
    path.join(outputDir, "manifest.json"),
    `${JSON.stringify(preparedManifest, null, 2)}\n`,
  );

  return preparedManifest;
}

function usage(): string {
  return [
    "Usage: deno task firefox-tests:prepare-browser [options]",
    "",
    "Options:",
    `  --collection <path>  Locked Firefox test collection (default: ${DEFAULT_COLLECTION_DIR})`,
    `  --out <path>         Generated wrapper output directory (default: ${DEFAULT_OUTPUT_DIR})`,
    "  --help, -h           Show this help",
  ].join("\n");
}

export async function main(args: string[]): Promise<void> {
  const parsed = parseArgs(args, {
    string: ["collection", "out"],
    boolean: ["help"],
    alias: { h: "help" },
    default: {
      collection: DEFAULT_COLLECTION_DIR,
      out: DEFAULT_OUTPUT_DIR,
    },
  });

  if (parsed.help) {
    console.log(usage());
    return;
  }
  if (parsed._.length > 0) {
    throw new Error(`Unexpected positional arguments: ${parsed._.join(" ")}`);
  }

  const manifest = await prepareFirefoxBrowserTests({
    collectionDir: ensureString(parsed.collection, "--collection"),
    outputDir: ensureString(parsed.out, "--out"),
  });

  console.log(
    `Prepared ${manifest.tests.length} locked Firefox browser test wrapper(s).`,
  );
  for (const test of manifest.tests) {
    console.log(`- ${test.wrapperPath} -> ${test.upstreamPath}`);
  }
}

if (import.meta.main) {
  try {
    await main(Deno.args);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.error(`[firefox-tests] ${message}`);
    Deno.exit(1);
  }
}
