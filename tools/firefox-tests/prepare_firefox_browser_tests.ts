import { parseArgs } from "@std/cli";
import * as path from "@std/path";

interface FirefoxTestCollectionManifest {
  schemaVersion: number;
  source?: {
    repository?: string;
    ref?: string;
    commit?: string;
  };
  files?: Array<{
    path: string;
    outputPath: string;
    roles?: string[];
    harnesses?: string[];
  }>;
}

type AllowlistEntry =
  | string
  | {
    path: string;
    name?: string;
    note?: string;
  };

interface NormalizedAllowlistEntry {
  path: string;
  name?: string;
  note?: string;
}

interface PreparedFirefoxBrowserTest {
  upstreamPath: string;
  wrapperPath: string;
  importSpecifier: string;
  note?: string;
}

interface PrepareFirefoxBrowserTestsOptions {
  collectionDir: string;
  allowlistPath: string;
  outputDir: string;
}

interface PreparedFirefoxBrowserTestsManifest {
  schemaVersion: 1;
  generatedAt: string;
  source: {
    repository: string;
    ref: string;
    commit: string;
  };
  collectionDir: string;
  allowlistPath: string;
  tests: PreparedFirefoxBrowserTest[];
}

const DEFAULT_COLLECTION_DIR = "_dist/firefox-tests";
const DEFAULT_ALLOWLIST_PATH =
  "browser-features/chrome/test/firefox-downloaded/allowlist.json";
const DEFAULT_OUTPUT_DIR =
  "browser-features/chrome/test/firefox-downloaded/generated";

function normalizeUpstreamPath(value: string): string {
  return value.replaceAll("\\", "/").replace(/^\/+/, "");
}

function ensureString(value: unknown, name: string): string {
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(`${name} is required`);
  }
  return value;
}

async function readJsonFile<T>(filePath: string): Promise<T> {
  const raw = await Deno.readTextFile(filePath);
  return JSON.parse(raw) as T;
}

function normalizeAllowlistEntry(
  entry: AllowlistEntry,
): NormalizedAllowlistEntry {
  if (typeof entry === "string") {
    return { path: normalizeUpstreamPath(entry) };
  }
  return {
    path: normalizeUpstreamPath(ensureString(entry.path, "allowlist path")),
    name: entry.name,
    note: entry.note,
  };
}

function sanitizeName(value: string): string {
  return value
    .replace(/\.[^.]+$/, "")
    .replace(/[^A-Za-z0-9_-]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .toLowerCase();
}

function wrapperNameForEntry(
  entry: NormalizedAllowlistEntry,
  usedNames: Set<string>,
): string {
  const explicitName = entry.name ? sanitizeName(entry.name) : "";
  const pathName = sanitizeName(entry.path.split("/").join("__"));
  const baseName = explicitName || pathName;
  if (!baseName) {
    throw new Error(`Could not derive wrapper name for ${entry.path}`);
  }

  let candidate = `${baseName}.test.js`;
  let suffix = 2;
  while (usedNames.has(candidate)) {
    candidate = `${baseName}-${suffix}.test.js`;
    suffix++;
  }
  usedNames.add(candidate);
  return candidate;
}

function buildWrapperSource(entry: NormalizedAllowlistEntry): string {
  const importSpecifier = `#firefox-tests/${entry.path}`;
  const noteLines = entry.note ? [`// Note: ${entry.note}`] : [];
  return [
    "// SPDX-License-Identifier: MPL-2.0",
    "// @colocated-env browser",
    "// @ts-nocheck",
    "//",
    "// Generated by tools/firefox-tests/prepare_firefox_browser_tests.ts.",
    "// Do not edit this file; edit allowlist.json instead.",
    `// Upstream path: ${entry.path}`,
    ...noteLines,
    "",
    `import ${JSON.stringify(importSpecifier)};`,
    "",
  ].join("\n");
}

async function assertCollectionFileExists(
  collectionDir: string,
  manifest: FirefoxTestCollectionManifest,
  upstreamPath: string,
): Promise<void> {
  const file = manifest.files?.find((entry) => entry.path === upstreamPath);
  if (!file) {
    throw new Error(
      `Allowlisted Firefox test is missing from collection manifest: ${upstreamPath}`,
    );
  }

  const outputPath = path.join(collectionDir, ...file.outputPath.split("/"));
  const stat = await Deno.stat(outputPath).catch((error) => {
    if (error instanceof Deno.errors.NotFound) {
      return null;
    }
    throw error;
  });
  if (!stat?.isFile) {
    throw new Error(
      `Allowlisted Firefox test blob is missing from collection: ${outputPath}`,
    );
  }
}

export async function prepareFirefoxBrowserTests(
  options: PrepareFirefoxBrowserTestsOptions,
): Promise<PreparedFirefoxBrowserTestsManifest> {
  const collectionDir = path.resolve(options.collectionDir);
  const allowlistPath = path.resolve(options.allowlistPath);
  const outputDir = path.resolve(options.outputDir);
  const collectionManifestPath = path.join(collectionDir, "manifest.json");

  const collectionManifest = await readJsonFile<FirefoxTestCollectionManifest>(
    collectionManifestPath,
  );
  const allowlist = await readJsonFile<AllowlistEntry[]>(allowlistPath);
  const entries = allowlist.map(normalizeAllowlistEntry);

  await Deno.remove(outputDir, { recursive: true }).catch((error) => {
    if (!(error instanceof Deno.errors.NotFound)) {
      throw error;
    }
  });
  await Deno.mkdir(outputDir, { recursive: true });

  const usedNames = new Set<string>();
  const preparedTests: PreparedFirefoxBrowserTest[] = [];

  for (const entry of entries) {
    await assertCollectionFileExists(
      collectionDir,
      collectionManifest,
      entry.path,
    );
    const wrapperName = wrapperNameForEntry(entry, usedNames);
    const wrapperPath = path.join(outputDir, wrapperName);
    await Deno.writeTextFile(wrapperPath, buildWrapperSource(entry));
    preparedTests.push({
      upstreamPath: entry.path,
      wrapperPath: path.relative(Deno.cwd(), wrapperPath).replaceAll("\\", "/"),
      importSpecifier: `#firefox-tests/${entry.path}`,
      note: entry.note,
    });
  }

  const preparedManifest: PreparedFirefoxBrowserTestsManifest = {
    schemaVersion: 1,
    generatedAt: new Date().toISOString(),
    source: {
      repository: collectionManifest.source?.repository ?? "",
      ref: collectionManifest.source?.ref ?? "",
      commit: collectionManifest.source?.commit ?? "",
    },
    collectionDir: path.relative(Deno.cwd(), collectionDir).replaceAll(
      "\\",
      "/",
    ),
    allowlistPath: path.relative(Deno.cwd(), allowlistPath).replaceAll(
      "\\",
      "/",
    ),
    tests: preparedTests,
  };
  await Deno.writeTextFile(
    path.join(outputDir, "manifest.json"),
    `${JSON.stringify(preparedManifest, null, 2)}\n`,
  );

  return preparedManifest;
}

function usage(): string {
  return [
    "Usage: deno task firefox-tests:prepare-browser [options]",
    "",
    "Options:",
    `  --collection <path>  Collected Firefox test directory (default: ${DEFAULT_COLLECTION_DIR})`,
    `  --allowlist <path>   Allowlist JSON file (default: ${DEFAULT_ALLOWLIST_PATH})`,
    `  --out <path>         Generated wrapper output directory (default: ${DEFAULT_OUTPUT_DIR})`,
    "  --help, -h           Show this help",
  ].join("\n");
}

export async function main(args: string[]): Promise<void> {
  const parsed = parseArgs(args, {
    string: ["collection", "allowlist", "out"],
    boolean: ["help"],
    alias: { h: "help" },
    default: {
      collection: DEFAULT_COLLECTION_DIR,
      allowlist: DEFAULT_ALLOWLIST_PATH,
      out: DEFAULT_OUTPUT_DIR,
    },
  });

  if (parsed.help) {
    console.log(usage());
    return;
  }
  if (parsed._.length > 0) {
    throw new Error(`Unexpected positional arguments: ${parsed._.join(" ")}`);
  }

  const manifest = await prepareFirefoxBrowserTests({
    collectionDir: ensureString(parsed.collection, "--collection"),
    allowlistPath: ensureString(parsed.allowlist, "--allowlist"),
    outputDir: ensureString(parsed.out, "--out"),
  });

  console.log(
    `Prepared ${manifest.tests.length} downloaded Firefox browser test wrapper(s).`,
  );
  for (const test of manifest.tests) {
    console.log(`- ${test.wrapperPath} -> ${test.upstreamPath}`);
  }
}

if (import.meta.main) {
  try {
    await main(Deno.args);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    console.error(`[firefox-tests] ${message}`);
    Deno.exit(1);
  }
}
