import * as path from "@std/path";
import { PATHS, PROJECT_ROOT } from "./defines.ts";
import { Logger } from "./utils.ts";
import { readBuildid2 } from "./update.ts";
import {
  marionettePortForOffset,
  requireDevPortOffset,
} from "#libs/shared/dev-ports/defines.ts";
import { OS_SERVER_PORT_PREF, osServerPortForOffset } from "./port_offset.ts";

const logger = new Logger("dev-env");

export type DevEnvProfileOptions = {
  allowBrowserHttpLoader?: boolean;
  /**
   * Dev/test port offset of the launch that owns this profile (FDH Gate 2
   * task 2-B). When > 0 the profile gets `nora.dev.port_offset` for the
   * browser-side port resolver and `marionette.port` = browserRemote + offset
   * so Marionette cannot overlap between concurrent worktrees. When 0
   * (default/absent) the user.js keeps the pre-offset port behavior for the
   * Vite/Marionette ports. The Floorp OS-Server pref (KAN-135) is written at
   * every offset: dev launches bind the dev-only in-span port so the default
   * and ladder offsets never collide with a concurrently running installed
   * Floorp on the packaged production default (the hand-picked offset 53086
   * lands back on 58261; the launch probe set and the OS-Server bind error
   * catch that occupied port instead of silently sharing it).
   */
  portOffset?: number;
};

const CHROME_BASELINE_CSP_PREF =
  'user_pref("security.chrome_baseline_csp.enabled", false);';

function buildUserJs(options: DevEnvProfileOptions = {}): string {
  const allowBrowserHttpLoader = options.allowBrowserHttpLoader ?? false;
  const portOffset = requireDevPortOffset(options.portOffset ?? 0);

  return `/**
 *! DO NOT EDIT THIS FILE.
 *
 ** This file is AUTOGENERATED
 ** Please modify the 'scripts/launchBrowser/savePrefs.ts' in the repo.
 * https://github.com/nyanrus/noraneko
 */

user_pref("devtools.debugger.prompt-connection",false);
user_pref("security.disallow_privileged_https_script_loads", false);
user_pref("security.allow_parent_unrestricted_js_loads", true);
user_pref("security.sandbox.content.level", 1);
user_pref("remote.active-protocols", 1);
user_pref("browser.newtabpage.enabled", true);
user_pref("floorp.mcp.enabled", true);
// Dev/test profile isolation; runtime also requires a dev/test startup marker.
user_pref("nora.dev.os_server.profile_token_file", ${allowBrowserHttpLoader});
// Dev-only Floorp OS-Server port (KAN-135): the in-span dev port shifted by
// the launch offset. The default and ladder offsets avoid the packaged
// production default 58261; the hand-picked offset 53086 would land back on
// it, which the launch probe set (auto/guard) and the OS-Server bind error
// catch instead of silently sharing the port.
user_pref("${OS_SERVER_PORT_PREF}", ${osServerPortForOffset(portOffset)});
user_pref("browser.sessionstore.resume_from_crash", false);
user_pref("nora.dev.allow_http_loader", ${allowBrowserHttpLoader});
${
    portOffset > 0
      ? `user_pref("marionette.port", ${marionettePortForOffset(portOffset)});
user_pref("nora.dev.port_offset", ${portOffset});
`
      : ""
  }${allowBrowserHttpLoader ? `${CHROME_BASELINE_CSP_PREF}\n` : ""}`;
}

/**
 * Remove the launch-ownership prefs left in `prefs.js` by a previous run of
 * this same profile. `user.js` overrides them on startup, but an offset-0
 * launch has no offset pref in `user.js`, so a reused profile would otherwise
 * keep resolving the previous offset (KAN-120, 2-B).
 */
function clearStaleLaunchPrefs(profileDir: string): void {
  const prefsPath = path.join(profileDir, "prefs.js");
  let content: string;
  try {
    content = Deno.readTextFileSync(prefsPath);
  } catch (e) {
    if (e instanceof Deno.errors.NotFound) return;
    logger.warn(`Failed to read prefs.js: ${(e as Error).message}`);
    return;
  }
  const kept = content.split("\n").filter((line) => {
    const trimmed = line.trim();
    return !trimmed.startsWith('user_pref("nora.dev.port_offset"') &&
      !trimmed.startsWith('user_pref("marionette.port"') &&
      // KAN-135: a reused profile must not keep a stale shifted OS-Server
      // port from a previous launch of this profile.
      !trimmed.startsWith('user_pref("floorp.os.server.port"');
  });
  if (kept.length === content.split("\n").length) return;
  try {
    Deno.writeTextFileSync(prefsPath, kept.join("\n"));
    logger.success(`Cleared stale launch prefs from ${prefsPath}`);
  } catch (e) {
    logger.warn(`Failed to clear prefs.js: ${(e as Error).message}`);
  }
}

export function savePrefs(
  profileDir: string,
  options: DevEnvProfileOptions = {},
): void {
  try {
    Deno.mkdirSync(profileDir, { recursive: true });
    const p = path.join(profileDir, "user.js");
    Deno.writeTextFileSync(p, buildUserJs(options));
    logger.success(`user.js written to ${p}`);
    clearStaleLaunchPrefs(profileDir);
    // deno-lint-ignore no-explicit-any
  } catch (e: any) {
    logger.error(`Failed to write user.js: ${e?.message ?? e}`);
  }
}

export function writeDevVersionInfo(): void {
  const gecko = path.join(PROJECT_ROOT, "static", "gecko");
  const dist = path.join(PROJECT_ROOT, "_dist");
  try {
    Deno.mkdirSync(dist, { recursive: true });
    Deno.mkdirSync(path.join(gecko, "config"), { recursive: true });

    Deno.writeTextFileSync(
      path.join(gecko, "config", "version.txt"),
      "version: 1.0.0\n",
    );
    const buildid2 = readBuildid2(PATHS.buildid2);
    if (buildid2 === null) {
      throw new Error(`buildid2 file not found at ${PATHS.buildid2}`);
    }
    Deno.writeTextFileSync(
      path.join(dist, "buildid2.txt"),
      `buildid2: ${buildid2}\n`,
    );
    logger.success("Wrote dev version info.");
    // deno-lint-ignore no-explicit-any
  } catch (e: any) {
    logger.error(`Failed to write dev version info: ${e?.message ?? e}`);
  }
}

export function setup(options: DevEnvProfileOptions = {}): void {
  // The profile dir used by browser launcher
  savePrefs(PATHS.profile_test, options);
  writeDevVersionInfo();
}
